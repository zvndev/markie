//! `pdf-styles.ts`: the standalone stylesheet and page around an export.
//! The CSS and the fit script are the Electron text, extracted verbatim into
//! `assets/` (a test checks them against Electron's own output).

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Theme {
    Light,
    Dark,
}

impl Theme {
    pub fn name(self) -> &'static str {
        match self {
            Theme::Light => "light",
            Theme::Dark => "dark",
        }
    }
}

pub const SHARED_CSS: &str = include_str!("assets/pdf-shared.css");
pub const DARK_CSS: &str = include_str!("assets/pdf-dark.css");
pub const LIGHT_CSS: &str = include_str!("assets/pdf-light.css");
pub const MATH_CSS: &str = include_str!("assets/pdf-math.css");
pub const FIT_SCRIPT: &str = include_str!("assets/fit-script.js");

/// `KATEX_CSS` (`katex-css.generated.ts`): KaTeX's stylesheet with 12 of its
/// fonts as data: URIs, which Electron puts first in every export page. Math
/// in an export is KaTeX's HTML (math_html.rs), so it needs the same rules and
/// fonts to draw as Electron's does. Regenerated by `scripts/katex-goldens.mjs`.
pub const KATEX_CSS: &str = include_str!("assets/katex.css");

/// What an export is drawn in beyond its theme: the Markdown style on
/// screen and the typefaces it is set in (`PDFOptions` in pdf-styles.ts and
/// `ExportFontChoice` in export-fonts.ts). The default adds nothing, so such
/// an export is the same bytes it always was.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct ExportLook {
    /// The Markdown style, or None for Spacious.
    pub style: Option<markie_core::markdown_style::MarkdownStyle>,
    /// Typeface ids from the font registry: "" or `system` for the export's
    /// own text face, "" or `body` for headings that follow the text, and ""
    /// for the export's own code face.
    pub body_font: String,
    pub heading_font: String,
    pub code_font: String,
}

/// A style's rules read the app's theme variables. An exported page has
/// none, so each export theme names its own colours for them (`STYLE_VARS`).
fn style_vars(theme: Theme) -> &'static str {
    match theme {
        Theme::Dark => "--background: #09090b; --foreground: #fafafa; --muted: #a1a1aa; --surface: #18181b; --doc-rule: #27272a; --accent: #3f3f46; --blue: #60a5fa; --purple: #c084fc; --status-yellow: #fb923c;",
        Theme::Light => "--background: #fff; --foreground: #1a1a2e; --muted: #71717a; --surface: #f4f4f5; --doc-rule: #e4e4e7; --accent: #e4e4e7; --blue: #2563eb; --purple: #8b5cf6; --status-yellow: #c2410c;",
    }
}

/// `markdownStyleBlock`: the rules that turn the export's own look into
/// `style`. Empty for Spacious.
pub fn markdown_style_block(theme: Theme, style: Option<&markie_core::markdown_style::MarkdownStyle>) -> String {
    let Some(style) = style else { return String::new() };
    let css = markie_core::markdown_style::css(&markie_core::markdown_style::resolve(style), ".markdown-body");
    // Generated from ids and numbers only, but this lands inside a <style>
    // element, so the one sequence that could end it is refused outright.
    if css.is_empty() || css.to_ascii_lowercase().contains("</style") {
        return String::new();
    }
    format!("\n  /* Markdown style */\n  .markdown-body {{ {} }}\n{css}\n", style_vars(theme))
}

// The app's own custom properties mean nothing in an exported file.
const SYSTEM_SANS: &str = "-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif";
const SYSTEM_MONO: &str = "'SF Mono', 'Cascadia Code', Menlo, Consolas, monospace";

fn standalone(stack: &str) -> String {
    stack.replace("var(--font-geist-sans)", SYSTEM_SANS).replace("var(--font-geist-mono)", SYSTEM_MONO)
}

fn stack_of(id: &str) -> String {
    markie_core::fonts::find_typeface(id).or_else(|| markie_core::fonts::find_typeface("system")).map(|f| f.stack).unwrap_or_default()
}

/// `exportFontRules`: the rules that set an exported document in the chosen
/// faces. No font files.
pub fn export_font_rules(look: &ExportLook) -> String {
    let mut rules: Vec<String> = Vec::new();
    if !matches!(look.body_font.as_str(), "" | "system") {
        rules.push(format!("body,.markdown-body{{font-family:{}}}", standalone(&stack_of(&look.body_font))));
    }
    if !matches!(look.heading_font.as_str(), "" | "body") {
        rules.push(format!(".markdown-body :is(h1,h2,h3,h4,h5,h6){{font-family:{}}}", standalone(&stack_of(&look.heading_font))));
    }
    let code = markie_core::fonts::clean_code_font(&look.code_font);
    if !code.is_empty() {
        rules.push(format!(".markdown-body :is(code,pre,kbd,samp),.markdown-body pre code{{font-family:{};font-variant-ligatures:none}}", standalone(&stack_of(&code))));
    }
    rules.join("\n")
}

/// `bundledFamiliesInHtml`: bundled families a document's own inline font
/// styles name.
fn bundled_families_in_html(html: &str) -> Vec<&'static markie_core::fonts::BundledFamily> {
    let lower = html.to_lowercase();
    let mut named = String::new();
    let mut rest = lower.as_str();
    while let Some(at) = rest.find("font-family") {
        let after = &rest[at + "font-family".len()..];
        let Some(colon) = after.trim_start().strip_prefix(':') else {
            rest = after;
            continue;
        };
        let end = colon.find([';', '"', '<', '>']).unwrap_or(colon.len()).min(400);
        let mut cut = end;
        while !colon.is_char_boundary(cut) {
            cut -= 1;
        }
        named.push_str(&colon[..cut]);
        named.push('\n');
        rest = &colon[cut..];
    }
    if named.is_empty() {
        return Vec::new();
    }
    markie_core::fonts::bundled_families().iter().filter(|f| named.contains(&f.family.to_lowercase())).collect()
}

/// `exportFontCss`: the stylesheet an export adds for fonts: the files,
/// inside the sheet as data: URLs, for every bundled face the look or the
/// document's own text uses, and the rules that apply the look's faces.
/// Empty when there is nothing to add.
pub fn export_font_css(html: &str, look: &ExportLook) -> String {
    use base64::Engine;
    let code = markie_core::fonts::clean_code_font(&look.code_font);
    let mut used = markie_core::fonts::bundled_families_used(&[look.body_font.as_str(), look.heading_font.as_str(), code.as_str()], &[]);
    for family in bundled_families_in_html(html) {
        if !used.iter().any(|f| f.id == family.id) {
            used.push(family);
        }
    }
    // Registry order, as Electron writes them.
    let families: Vec<&markie_core::fonts::BundledFamily> = markie_core::fonts::bundled_families().iter().filter(|f| used.iter().any(|u| u.id == f.id)).collect();
    let faces = markie_core::fonts::font_face_rules(
        |file| markie_core::fonts::bundled_file(file).map(|bytes| format!("data:font/woff2;base64,{}", base64::engine::general_purpose::STANDARD.encode(bytes))),
        &families,
    );
    [faces, export_font_rules(look)].into_iter().filter(|part| !part.is_empty()).collect::<Vec<_>>().join("\n")
}

/// `fontBlock`: the font stylesheet in a style element of its own, after the
/// page's, or "" for none.
fn font_block(font_css: &str) -> String {
    if font_css.is_empty() {
        return String::new();
    }
    // `</style` cannot close the element from inside it.
    let mut safe = String::with_capacity(font_css.len());
    let lower = font_css.to_ascii_lowercase();
    let mut at = 0;
    while let Some(found) = lower[at..].find("</style") {
        let i = at + found;
        safe.push_str(&font_css[at..i]);
        safe.push_str("<\\/");
        safe.push_str(&font_css[i + 2..i + 7]);
        at = i + 7;
    }
    safe.push_str(&font_css[at..]);
    format!("\n<style>{safe}</style>")
}

/// `getPDFStyles`: the `<style>` element, KaTeX's stylesheet first.
pub fn pdf_styles(theme: Theme) -> String {
    pdf_styles_with(theme, None)
}

/// `getPDFStyles` with a Markdown style's rules after the export's own.
pub fn pdf_styles_with(theme: Theme, style: Option<&markie_core::markdown_style::MarkdownStyle>) -> String {
    let body = match theme {
        Theme::Dark => DARK_CSS,
        Theme::Light => LIGHT_CSS,
    };
    format!("<style>{KATEX_CSS}\n{SHARED_CSS}\n{body}\n{MATH_CSS}{}</style>", markdown_style_block(theme, style))
}

/// `neutralizeBodyBreakouts`: a template-integrity guard, not a sanitizer.
pub fn neutralize_body_breakouts(html: &str) -> String {
    let mut out = String::with_capacity(html.len());
    let mut rest = html;
    while let Some(at) = rest.find('<') {
        out.push_str(&rest[..at]);
        let after = &rest[at + 1..];
        let (slash, name_at) = if let Some(s) = after.strip_prefix('/') { ("/", s) } else { ("", after) };
        let lower: String = name_at.chars().take(6).collect::<String>().to_ascii_lowercase();
        let hit = ["script", "style"].into_iter().find(|n| {
            lower.starts_with(n) && !name_at[n.len()..].starts_with(|c: char| c.is_alphanumeric() || c == '_')
        });
        match hit {
            Some(n) => {
                out.push_str("&lt;");
                out.push_str(slash);
                out.push_str(&name_at[..n.len()]);
                rest = &name_at[n.len()..];
            }
            None => {
                out.push('<');
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

/// `buildPDFHTML`: the whole standalone document.
pub fn build_pdf_html(markdown_html: &str, theme: Theme) -> String {
    build_pdf_html_with(markdown_html, theme, &ExportLook::default())
}

/// `buildPDFHTML` drawn in a Markdown style and its fonts: the style's rules
/// after the export's own, and the bundled faces it uses inside the file.
pub fn build_pdf_html_with(markdown_html: &str, theme: Theme, look: &ExportLook) -> String {
    format!(
        "<!DOCTYPE html>\n<html>\n<head>\n<meta charset=\"utf-8\">\n<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n{}{}\n<script>{FIT_SCRIPT}</script>\n</head>\n<body>\n<article class=\"markdown-body\">{}</article>\n</body>\n</html>",
        pdf_styles_with(theme, look.style.as_ref()),
        font_block(&export_font_css(markdown_html, look)),
        neutralize_body_breakouts(markdown_html)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn breakouts_are_neutralized() {
        assert_eq!(neutralize_body_breakouts("<p>a</p><script>x</script><STYLE>"), "<p>a</p>&lt;script>x&lt;/script>&lt;STYLE>");
        assert_eq!(neutralize_body_breakouts("<scripts>"), "<scripts>");
    }

    #[test]
    fn the_default_look_adds_nothing_to_an_export() {
        let plain = build_pdf_html("<p>a</p>", Theme::Light);
        assert_eq!(build_pdf_html_with("<p>a</p>", Theme::Light, &ExportLook::default()), plain);
        let spacious = ExportLook { style: Some(Default::default()), body_font: "system".into(), heading_font: "body".into(), ..Default::default() };
        assert_eq!(build_pdf_html_with("<p>a</p>", Theme::Light, &spacious), plain);
        assert_eq!(plain.matches("<style>").count(), 1);
    }

    #[test]
    fn an_export_carries_its_style_and_only_the_fonts_it_uses() {
        use markie_core::markdown_style::MarkdownStyle;
        let look = ExportLook { style: Some(MarkdownStyle::preset("editorial")), body_font: "source-serif".into(), heading_font: "playfair".into(), code_font: "fira-code".into() };
        let html = build_pdf_html_with("<h1>T</h1><p style=\"font-family: 'Caveat', cursive\">x</p>", Theme::Dark, &look);
        // The style's rules, after the export's own, with the theme's colours named.
        let block = markdown_style_block(Theme::Dark, look.style.as_ref());
        assert!(block.starts_with("\n  /* Markdown style */\n  .markdown-body { --background: #09090b;"));
        assert!(block.contains(".markdown-body blockquote { border-left: none;"));
        assert!(html.contains(&format!("{MATH_CSS}{block}</style>")));
        // The faces: the three the look names and the one the document's own text names.
        let fonts = export_font_css("<p style=\"font-family: 'Caveat', cursive\">x</p>", &look);
        for family in ["'Source Serif 4'", "'Playfair Display'", "'Fira Code'", "'Caveat'"] {
            assert!(fonts.contains(&format!("@font-face{{font-family:{family};")), "{family}");
        }
        assert!(!fonts.contains("'Inter'"));
        assert!(fonts.contains("src:url(\"data:font/woff2;base64,d09GMg"), "woff2 files, inside the sheet");
        assert!(fonts.ends_with(
            "body,.markdown-body{font-family:'Source Serif 4', Georgia, 'Times New Roman', serif}\n.markdown-body :is(h1,h2,h3,h4,h5,h6){font-family:'Playfair Display', Georgia, 'Times New Roman', serif}\n.markdown-body :is(code,pre,kbd,samp),.markdown-body pre code{font-family:'Fira Code', ui-monospace, 'SF Mono', Menlo, Consolas, 'Liberation Mono', monospace;font-variant-ligatures:none}"
        ));
        assert_eq!(html.matches("<style>").count(), 2);
        // System faces add rules and no files; the app's own variables are written out.
        let system = ExportLook { body_font: "charter".into(), heading_font: "mono".into(), code_font: "inter".into(), ..Default::default() };
        assert_eq!(
            export_font_css("", &system),
            "body,.markdown-body{font-family:Charter, 'Bitstream Charter', Georgia, 'Times New Roman', serif}\n.markdown-body :is(h1,h2,h3,h4,h5,h6){font-family:'SF Mono', 'Cascadia Code', Menlo, Consolas, monospace}"
        );
        assert_eq!(font_block("a</STYLE>b"), "\n<style>a<\\/STYLEb</style>".replace("STYLEb", "STYLE>b"));
    }

    #[test]
    fn fit_script_never_closes_itself() {
        assert!(!FIT_SCRIPT.to_ascii_lowercase().contains("</script"));
    }
}
