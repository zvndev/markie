// Rebuild only the reviewed browser entry points, never a Darkmown project or CLI.
// Usage: node scripts/build-darkmown-vendor.mjs --source /path/to/darkmown [--check]
import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const SOURCE_COMMIT = "f3023a444696bcbcbc0475d718889291d88af7b1";
const ESBUILD_VERSION = "0.28.2";
const root = fileURLToPath(new URL("..", import.meta.url));
const destination = path.join(root, "src/lib/darkmown/vendor");
const bootstrapPath = "src/lib/darkmown/local-form-bootstrap.js.txt";
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const posix = (value) => value.split(path.sep).join("/");

async function main() {
  const sourceIndex = process.argv.indexOf("--source");
  if (sourceIndex < 0 || !process.argv[sourceIndex + 1]) {
    throw new Error("Supply --source pointing at the pinned Darkmown checkout. Ordinary Markie builds use the committed artifacts and need no checkout.");
  }
  const source = await fs.realpath(path.resolve(process.argv[sourceIndex + 1]));
  const git = (...args) => execFileSync("git", ["-C", source, ...args], { encoding: "utf8" }).trim();
  if (git("rev-parse", "HEAD") !== SOURCE_COMMIT || git("status", "--porcelain", "--untracked-files=no")) {
    throw new Error(`Darkmown must be a clean checkout at ${SOURCE_COMMIT}.`);
  }
  const { build, version } = await import(pathToFileURL(path.join(source, "node_modules/esbuild/lib/main.js")).href);
  if (version !== ESBUILD_VERSION) throw new Error(`Expected esbuild ${ESBUILD_VERSION}, found ${version}.`);
  const packageInfo = JSON.parse(await fs.readFile(path.join(source, "package.json"), "utf8"));
  const bootstrap = await fs.readFile(path.join(root, bootstrapPath), "utf8");
  if (/<\/script/i.test(bootstrap)) throw new Error("The local form bootstrap cannot be safely embedded in an HTML script element.");
  const common = {
    absWorkingDir: source,
    bundle: true,
    write: false,
    platform: "browser",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    metafile: true,
    logLevel: "warning",
    banner: { js: "/* eslint-disable */\n// Generated by scripts/build-darkmown-vendor.mjs. See PROVENANCE.json and THIRD-PARTY-NOTICES.txt." },
  };
  const compiler = await build({
    ...common,
    stdin: { contents: 'export { compileFromMemory } from "./src/compiler/page.js";', resolveDir: source, sourcefile: "markie-browser-entry.js", loader: "js" },
    format: "esm",
    outfile: "compiler-browser.mjs",
    alias: {
      "node:path": path.join(source, "scripts/playground/shims/path.js"),
      "node:crypto": path.join(source, "scripts/playground/shims/crypto.js"),
      "highlight.js": "highlight.js/lib/common",
    },
  });
  const runtime = await build({ ...common, entryPoints: ["src/runtime.js"], format: "iife", outfile: "runtime.js.txt" });
  if (/<\/script/i.test(runtime.outputFiles[0].text)) throw new Error("Runtime cannot be safely embedded in an HTML script element.");
  const inputs = new Set([...Object.keys(compiler.metafile.inputs), ...Object.keys(runtime.metafile.inputs)]);
  inputs.delete("markie-browser-entry.js");
  const sourceFiles = [];
  const packages = new Map();
  packages.set("@zvndev/darkmown", { version: packageInfo.version, root: source, license: packageInfo.license });
  for (const relative of [...inputs].sort()) {
    const absolute = path.resolve(source, relative);
    if (path.relative(source, absolute).startsWith("..")) throw new Error("Unexpected compiler input outside the pinned checkout.");
    sourceFiles.push({ path: posix(relative), sha256: sha256(await fs.readFile(absolute)) });
    if (!relative.startsWith("node_modules/")) continue;
    let parent = path.dirname(absolute);
    while (parent !== source) {
      try {
        const info = JSON.parse(await fs.readFile(path.join(parent, "package.json"), "utf8"));
        if (info.name && info.version) {
          packages.set(info.name, { version: info.version, root: parent, license: info.license });
          break;
        }
      } catch (error) { if (error.code !== "ENOENT") throw error; }
      parent = path.dirname(parent);
    }
  }
  const notices = [];
  for (const [name, info] of [...packages].sort(([a], [b]) => a.localeCompare(b, "en"))) {
    const names = await fs.readdir(info.root);
    const license = names.find((name) => /^licen[sc]e(?:[.-].*)?$/i.test(name));
    if (!license) throw new Error(`No license notice found for bundled ${name}.`);
    notices.push(`${name} ${info.version} (${info.license})\n${await fs.readFile(path.join(info.root, license), "utf8")}`);
  }
  const artifacts = {
    "compiler-browser.mjs": compiler.outputFiles[0].text,
    "runtime.js.txt": runtime.outputFiles[0].text,
    "THIRD-PARTY-NOTICES.txt": `${notices.join("\n\n----------------------------------------\n\n").trimEnd()}\n`,
  };
  const manifest = {
    source: "https://github.com/ZVN-DEV/darkmown",
    commit: SOURCE_COMMIT,
    version: packageInfo.version,
    build: { script: "scripts/build-darkmown-vendor.mjs", scriptSha256: sha256(await fs.readFile(fileURLToPath(import.meta.url))), esbuild: version, sourceLockSha256: sha256(await fs.readFile(path.join(source, "package-lock.json"))) },
    entryPoints: ["src/compiler/page.js:compileFromMemory", "src/runtime.js"],
    browserShims: ["scripts/playground/shims/path.js", "scripts/playground/shims/crypto.js"],
    hostAdaptations: [{ path: bootstrapPath, bytes: Buffer.byteLength(bootstrap), sha256: sha256(bootstrap), purpose: "Fixed local-form event routing and one-way light/dark appearance projection inside the opaque sandbox. No native submission, network, document capabilities, credentials or replies." }],
    limitations: ["Only explicitly supplied virtual text files can be read.", "The scope-id hash shim is deterministic FNV-1a, not cryptographic SHA-256.", "Compiler output is not sanitized. The host must isolate and authorize runtime execution.", "Runtime storage, fetch, forms, navigation and media require host policy; this artifact grants no capability."],
    bundledPackages: [...packages].sort(([a], [b]) => a.localeCompare(b, "en")).map(([name, info]) => ({ name, version: info.version, license: info.license })),
    inputs: sourceFiles,
    artifacts: Object.fromEntries(Object.entries(artifacts).map(([name, content]) => [name, { bytes: Buffer.byteLength(content), sha256: sha256(content) }])),
  };
  artifacts["PROVENANCE.json"] = `${JSON.stringify(manifest, null, 2)}\n`;
  const policy = `${JSON.stringify({ runtimeSha256: createHash("sha256").update(artifacts["runtime.js.txt"]).digest("base64"), bootstrapSha256: createHash("sha256").update(bootstrap).digest("base64") }, null, 2)}\n`;
  const check = process.argv.includes("--check");
  const generated = new Map(Object.entries(artifacts).map(([name, content]) => [path.join(destination, name), content]));
  generated.set(path.join(root, "electron/darkmown-runtime-policy.json"), policy);
  for (const name of ["THIRD-PARTY-NOTICES.txt", "PROVENANCE.json"]) generated.set(path.join(root, "public/darkmown", name), artifacts[name]);
  for (const [target, content] of generated) {
    if (check) {
      if (await fs.readFile(target, "utf8") !== content) throw new Error(`Vendored Darkmown artifact drift: ${path.relative(root, target)}`);
    } else {
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, content);
    }
  }
  console.log(`${check ? "Verified" : "Generated"} pinned Darkmown ${packageInfo.version}: ${Object.keys(artifacts).join(", ")}`);
}

await main();
